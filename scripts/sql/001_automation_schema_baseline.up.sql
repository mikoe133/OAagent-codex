CREATE TABLE automation_job_runs (
    id CHAR(36) NOT NULL,
    root_run_id CHAR(36) NOT NULL,
    parent_run_id CHAR(36) NULL,
    job_id BIGINT NOT NULL,
    job_key_snapshot VARCHAR(100) NOT NULL,
    job_name_snapshot VARCHAR(255) NOT NULL,
    job_type_snapshot VARCHAR(100) NOT NULL,
    description_snapshot TEXT NOT NULL,
    tags_snapshot JSON NOT NULL,
    trigger_source VARCHAR(20) NOT NULL,
    scheduled_at DATETIME(6) NOT NULL,
    available_at DATETIME(6) NOT NULL,
    triggered_at DATETIME(6) NOT NULL,
    started_at DATETIME(6) NULL,
    finished_at DATETIME(6) NULL,
    status VARCHAR(32) NOT NULL,
    attempt INT NOT NULL DEFAULT 1,
    model_provider_snapshot VARCHAR(100) NOT NULL,
    model_id_snapshot VARCHAR(150) NOT NULL,
    model_parameters_snapshot JSON NOT NULL,
    model_catalog_version_snapshot VARCHAR(100) NULL,
    prompt_version_snapshot VARCHAR(100) NULL,
    system_prompt_snapshot MEDIUMTEXT NULL,
    cron_expression_snapshot VARCHAR(100) NOT NULL,
    timezone_snapshot VARCHAR(64) NOT NULL,
    retry_max_attempts_snapshot INT NOT NULL,
    retry_interval_seconds_snapshot INT NOT NULL,
    timeout_seconds_snapshot INT NOT NULL,
    deadline_at DATETIME(6) NOT NULL,
    worker_instance VARCHAR(255) NULL,
    lease_token_digest CHAR(64) NULL,
    lease_duration_seconds INT NULL,
    lease_expires_at DATETIME(6) NULL,
    heartbeat_at DATETIME(6) NULL,
    projects_total INT NOT NULL DEFAULT 0,
    projects_succeeded INT NOT NULL DEFAULT 0,
    projects_failed INT NOT NULL DEFAULT 0,
    mutations_applied TINYINT(1) NOT NULL DEFAULT 0,
    retry_recommended TINYINT(1) NOT NULL DEFAULT 0,
    duration_ms BIGINT NULL,
    error_code VARCHAR(100) NULL,
    error_summary VARCHAR(1000) NULL,
    cancel_requested_at DATETIME(6) NULL,
    cancel_requested_by INT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_automation_job_runs_schedule_attempt (job_id, scheduled_at, attempt),
    KEY idx_automation_job_runs_status_schedule (status, scheduled_at),
    KEY idx_automation_job_runs_pending (status, available_at),
    KEY idx_automation_job_runs_job_created (job_id, created_at),
    KEY idx_automation_job_runs_lease (lease_expires_at),
    KEY idx_automation_job_runs_root (root_run_id, attempt),
    CONSTRAINT fk_automation_job_runs_job FOREIGN KEY (job_id)
        REFERENCES automation_jobs (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_automation_job_runs_root FOREIGN KEY (root_run_id)
        REFERENCES automation_job_runs (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_automation_job_runs_parent FOREIGN KEY (parent_run_id)
        REFERENCES automation_job_runs (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_automation_job_runs_trigger CHECK (trigger_source IN ('schedule', 'manual', 'retry', 'catch_up')),
    CONSTRAINT chk_automation_job_runs_status CHECK (status IN ('pending', 'claimed', 'running', 'succeeded', 'partial_failed', 'failed', 'configuration_error', 'skipped', 'cancelled')),
    CONSTRAINT chk_automation_job_runs_attempt CHECK (attempt >= 1),
    CONSTRAINT chk_automation_job_runs_lease_duration CHECK (lease_duration_seconds IS NULL OR lease_duration_seconds BETWEEN 60 AND 600)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE automation_job_run_projects (
    id BIGINT NOT NULL AUTO_INCREMENT,
    run_id CHAR(36) NOT NULL,
    project_id INT NOT NULL,
    project_name_snapshot VARCHAR(255) NOT NULL,
    status_before VARCHAR(32) NULL,
    status_after VARCHAR(32) NULL,
    outcome VARCHAR(50) NOT NULL,
    repository_count INT NOT NULL DEFAULT 0,
    commit_count INT NOT NULL DEFAULT 0,
    summary_date DATE NULL,
    source_digest VARCHAR(128) NULL,
    generated_summary LONGTEXT NULL,
    ai_confidence INT NULL,
    ai_note TEXT NULL,
    warnings JSON NOT NULL,
    mutations_applied TINYINT(1) NOT NULL DEFAULT 0,
    started_at DATETIME(6) NULL,
    finished_at DATETIME(6) NULL,
    duration_ms BIGINT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_automation_run_projects_run_project (run_id, project_id),
    KEY idx_automation_run_projects_project (project_id, created_at),
    KEY idx_automation_run_projects_outcome (outcome),
    CONSTRAINT fk_automation_run_projects_run FOREIGN KEY (run_id)
        REFERENCES automation_job_runs (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_automation_run_projects_confidence CHECK (ai_confidence IS NULL OR ai_confidence BETWEEN 0 AND 100),
    CONSTRAINT chk_automation_run_projects_outcome CHECK (outcome IN ('evaluated', 'archived', 'no_github_urls', 'no_commits', 'invalid_github_urls', 'incomplete', 'write_conflict', 'failed'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

