CREATE TABLE automation_jobs (
    id BIGINT NOT NULL AUTO_INCREMENT,
    job_key VARCHAR(100) NOT NULL,
    job_type VARCHAR(100) NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    enabled TINYINT(1) NOT NULL DEFAULT 0,
    timezone VARCHAR(64) NOT NULL,
    schedule_type VARCHAR(20) NOT NULL DEFAULT 'cron',
    cron_expression VARCHAR(100) NOT NULL,
    catch_up_policy VARCHAR(20) NOT NULL DEFAULT 'latest',
    overlap_policy VARCHAR(20) NOT NULL DEFAULT 'forbid',
    model_provider VARCHAR(100) NOT NULL,
    model_id VARCHAR(150) NOT NULL,
    model_parameters JSON NOT NULL,
    model_catalog_version VARCHAR(100) NULL,
    retry_max_attempts INT NOT NULL DEFAULT 3,
    retry_interval_seconds INT NOT NULL DEFAULT 300,
    timeout_seconds INT NOT NULL DEFAULT 2700,
    retention_days INT NOT NULL DEFAULT 90,
    last_scheduled_at DATETIME(6) NULL,
    last_started_at DATETIME(6) NULL,
    last_finished_at DATETIME(6) NULL,
    next_run_at DATETIME(6) NULL,
    last_run_status VARCHAR(32) NULL,
    configuration_status VARCHAR(20) NOT NULL DEFAULT 'unverified',
    configuration_error VARCHAR(500) NULL,
    version INT NOT NULL DEFAULT 1,
    created_by INT NULL,
    updated_by INT NULL,
    deleted_at DATETIME(6) NULL,
    deleted_by INT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_automation_jobs_job_key (job_key),
    KEY idx_automation_jobs_due (enabled, next_run_at),
    KEY idx_automation_jobs_configuration (configuration_status),
    KEY idx_automation_jobs_model (model_provider, model_id),
    KEY idx_automation_jobs_deleted (deleted_at),
    CONSTRAINT chk_automation_jobs_enabled CHECK (enabled IN (0, 1)),
    CONSTRAINT chk_automation_jobs_schedule_type CHECK (schedule_type = 'cron'),
    CONSTRAINT chk_automation_jobs_catch_up CHECK (catch_up_policy IN ('skip', 'latest')),
    CONSTRAINT chk_automation_jobs_overlap CHECK (overlap_policy = 'forbid'),
    CONSTRAINT chk_automation_jobs_configuration CHECK (configuration_status IN ('valid', 'invalid', 'unverified')),
    CONSTRAINT chk_automation_jobs_retry_attempts CHECK (retry_max_attempts BETWEEN 1 AND 10),
    CONSTRAINT chk_automation_jobs_retry_interval CHECK (retry_interval_seconds BETWEEN 0 AND 86400),
    CONSTRAINT chk_automation_jobs_timeout CHECK (timeout_seconds BETWEEN 60 AND 86400),
    CONSTRAINT chk_automation_jobs_retention CHECK (retention_days BETWEEN 1 AND 3650)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE automation_tags (
    id BIGINT NOT NULL AUTO_INCREMENT,
    name VARCHAR(100) NOT NULL,
    normalized_name VARCHAR(100) NOT NULL,
    color VARCHAR(32) NULL,
    description VARCHAR(500) NOT NULL DEFAULT '',
    enabled TINYINT(1) NOT NULL DEFAULT 1,
    created_by INT NULL,
    updated_by INT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_automation_tags_normalized_name (normalized_name),
    KEY idx_automation_tags_enabled_name (enabled, name),
    CONSTRAINT chk_automation_tags_enabled CHECK (enabled IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE automation_job_tags (
    job_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (job_id, tag_id),
    UNIQUE KEY uq_automation_job_tags_job_tag (job_id, tag_id),
